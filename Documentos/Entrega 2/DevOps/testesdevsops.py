import unittest
from datetime import datetime

class TestAgendaConsulta(unittest.TestCase):

    def test_date_to_timestamp(self):

        def date_to_timestamp(dt_obj):
            if dt_obj:
                return int(dt_obj.timestamp() * 1000)
            return None

        now = datetime.now()
        ts = date_to_timestamp(now)

        self.assertIsNotNone(ts)
        self.assertIsInstance(ts, int)


        self.assertIsNone(date_to_timestamp(None))
        print(f"Teste Unitário concluído!!! Timestamp gerado: {ts}")
