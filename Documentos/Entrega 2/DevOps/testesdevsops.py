import unittest

class TestProgressoFisioterapia(unittest.TestCase):

    def test_calcular_progresso(self):
        exercicios = [
            {"concluido": True}, {"concluido": True},
            {"concluido": True}, {"concluido": False}
        ]

        def calcular_progresso(exs):
            if not exs:
                return 0
            concluidos = sum(1 for ex in exs if ex["concluido"])
            return (concluidos * 100) // len(exs)

        self.assertEqual(calcular_progresso(exercicios), 75)
        self.assertEqual(calcular_progresso([]), 0)

        print(f"Progresso calculado com sucesso (75%)")

if __name__ == '__main__':
    unittest.main(argv=['first-arg-is-ignored'], exit=False)

