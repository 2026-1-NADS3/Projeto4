import time
import random

def simulate_firebase_load(users):
    latencies = []
    for _ in range(users):
        start = time.time()
        time.sleep(random.uniform(0.1, 0.5))
        latencies.append(time.time() - start)

    avg_latency = sum(latencies) / users
    print(f"Relatório de Carga - Simulação {users} usuários")
    print(f"Tempo médio de resposta: {avg_latency:.2f}s")
    print("Status: Servidor Estável (Firebase Cloud)")

